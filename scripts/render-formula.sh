#!/usr/bin/env bash
# Render the Homebrew formula for a release from its .sha256 files.
#
# Usage: scripts/render-formula.sh <version> <dist-dir> [owner/repo]
#
# Expects <dist-dir> to contain sysfetch-<version>-<rid>.tar.gz.sha256 for
# osx-arm64, osx-x64, linux-arm64 and linux-x64. Writes the formula to stdout.
set -euo pipefail

if [[ $# -lt 2 || $# -gt 3 ]]; then
  echo "usage: $0 <version> <dist-dir> [owner/repo]" >&2
  exit 2
fi

version="$1"
dist_dir="$2"
repo="${3:-${GITHUB_REPOSITORY:-cprice70/sysfetch}}"

sha() {
  local file="$dist_dir/sysfetch-${version}-$1.tar.gz.sha256"
  if [[ ! -f "$file" ]]; then
    echo "error: missing $file" >&2
    exit 1
  fi
  local hash
  hash="$(cut -d' ' -f1 < "$file")"
  if [[ ! "$hash" =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: bad sha256 in $file" >&2
    exit 1
  fi
  echo "$hash"
}

osx_arm64="$(sha osx-arm64)"
osx_x64="$(sha osx-x64)"
linux_arm64="$(sha linux-arm64)"
linux_x64="$(sha linux-x64)"
base="https://github.com/${repo}/releases/download/v${version}"

cat <<EOF
# Generated by scripts/render-formula.sh for v${version}. Do not edit by hand.
class Sysfetch < Formula
  desc "Fast system information tool (Native AOT .NET)"
  homepage "https://github.com/${repo}"
  version "${version}"

  on_macos do
    on_arm do
      url "${base}/sysfetch-${version}-osx-arm64.tar.gz"
      sha256 "${osx_arm64}"
    end
    on_intel do
      url "${base}/sysfetch-${version}-osx-x64.tar.gz"
      sha256 "${osx_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/sysfetch-${version}-linux-arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/sysfetch-${version}-linux-x64.tar.gz"
      sha256 "${linux_x64}"
    end
  end

  def install
    bin.install "sysfetch"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sysfetch --version")
    system bin/"sysfetch", "--json", "--no-config"
  end
end
EOF
